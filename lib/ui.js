globalThis.PD = globalThis.PD || {};
PD.showWarning = function (r) {
  if (document.getElementById('phishguard-root')) return;
  const host = document.createElement('div');
  host.id = 'phishguard-root';
  host.style.cssText = 'position:fixed;inset:0;z-index:2147483647;';
  const sh = host.attachShadow({ mode: 'closed' });
  const color = r.level === 'High Risk' ? '#c62828' : '#ef6c00';
  const style = document.createElement('style');
  style.textContent = '.bg{position:fixed;inset:0;background:rgba(0,0,0,.75);display:flex;align-items:center;justify-content:center;font-family:system-ui,sans-serif}.box{background:#fff;color:#222;max-width:480px;width:90%;border-radius:12px;padding:24px;border-top:8px solid ' + color + '}h2{margin:0 0 8px;color:' + color + '}button{padding:10px 16px;border:0;border-radius:8px;font-size:15px;cursor:pointer;margin-right:8px}.back{background:' + color + ';color:#fff}.go{background:#eee}';
  const bg = document.createElement('div'); bg.className = 'bg';
  const box = document.createElement('div'); box.className = 'box';
  const h2 = document.createElement('h2');
  h2.textContent = r.level + ' (risk score ' + Math.round(r.score * 100) + '/100)';
  const ul = document.createElement('ul');
  r.reasons.slice(0, 8).forEach(t => { const li = document.createElement('li'); li.textContent = t; ul.appendChild(li); });
  const back = document.createElement('button'); back.className = 'back'; back.textContent = 'Go back';
  back.onclick = () => { if (history.length > 1) history.back(); else location.href = 'about:blank'; };
  const go = document.createElement('button'); go.className = 'go'; go.textContent = 'Proceed anyway';
  go.onclick = () => host.remove();
  box.append(h2, ul, back, go); bg.append(box); sh.append(style, bg);
  document.documentElement.appendChild(host);
};